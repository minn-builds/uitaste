import { existsSync, readFileSync, writeFileSync } from "node:fs";
import type { Plugin } from "vite";
import {
  generateTokens,
  listPresets,
  SEMANTIC_ROLES,
  type Tokens,
  toCssVars,
} from "../../packages/core/src/index.ts";

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/**
 * Scope the runtime `--tk-*` blocks of one preset to `:root[data-preset="id"]`.
 * Selectors may be indented (the dark block sits inside a prefers-color-scheme media query).
 */
export function scope(css: string, id: string): string {
  const root = `:root[data-preset="${id}"]`;
  return css
    .replace(/^(\s*):root:not\(\.light\)/gm, `$1${root}:not(.light)`)
    .replace(/^(\s*):root \{/gm, `$1${root} {`)
    .replace(/^\.dark \{/gm, `${root}.dark {`);
}

/** One shared `@theme inline` that maps every Tailwind theme key to the active preset's runtime vars. */
function sharedTheme(t: Tokens): string {
  const lines: string[] = ["  --color-*: initial;"];
  const map = (to: string, from: string) => lines.push(`  ${to}: var(${from});`);
  for (const role of SEMANTIC_ROLES) map(`--color-${kebab(role)}`, `--tk-color-${kebab(role)}`);
  for (const [name, ramp] of Object.entries(t.color.ramps)) {
    for (const step of Object.keys(ramp)) {
      map(`--color-${name}-${step}`, `--tk-ramp-${name}-${step}`);
    }
  }
  for (const k of Object.keys(t.font)) map(`--font-${k}`, `--tk-font-${k}`);
  for (const k of Object.keys(t.text)) {
    map(`--text-${k}`, `--tk-text-${k}`);
    map(`--text-${k}--line-height`, `--tk-text-${k}-line-height`);
  }
  map("--spacing", "--tk-space-1");
  for (const k of Object.keys(t.radius)) map(`--radius-${k}`, `--tk-radius-${k}`);
  for (const k of Object.keys(t.shadow)) map(`--shadow-${k}`, `--tk-shadow-${k}`);
  map("--default-transition-duration", "--tk-duration-base");
  map("--default-transition-timing-function", "--tk-easing");
  map("--ease-standard", "--tk-easing");
  return `@custom-variant dark (&:where(.dark, .dark *));\n\n@theme inline {\n${lines.join("\n")}\n}\n`;
}

/**
 * Writes src/tokens.generated.css and src/presets.generated.json from the real preset registry.
 * Each preset's vars are scoped under `:root[data-preset="<id>"]`; the Tailwind theme is shared.
 */
export function uitasteTokens(): Plugin {
  return {
    name: "uitaste-tokens",
    buildStart() {
      const loaded = listPresets();
      const all = loaded.map((l) => ({ id: l.preset.meta.id, tokens: generateTokens(l.preset) }));
      const first = all[0];
      if (!first) throw new Error("No presets found in @uitaste/presets");
      const css = [
        `/* Generated by uitaste-tokens-plugin.ts. Do not edit. */`,
        ...all.map((p) => scope(toCssVars(p.tokens), p.id)),
        sharedTheme(first.tokens),
      ].join("\n");
      writeFileSync(new URL("./src/tokens.generated.css", import.meta.url), css);
      const metaUrl = new URL("./src/presets.generated.json", import.meta.url);
      const meta = JSON.stringify(
        loaded.map((l) => l.preset.meta),
        null,
        2,
      );
      // Skip the write when unchanged so the committed (biome-formatted) file stays stable.
      const same =
        existsSync(metaUrl) &&
        JSON.stringify(JSON.parse(readFileSync(metaUrl, "utf8")), null, 2) === meta;
      if (!same) writeFileSync(metaUrl, `${meta}\n`);
    },
  };
}
